// Generates src/schema/generated.ts from the TypeScript types. Never edit generated.ts by hand.
//   node scripts/gen-schema.mjs           write (and format) the file
//   node scripts/gen-schema.mjs --check   exit 1 when the committed file differs from a fresh generation
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { createGenerator } from "ts-json-schema-generator";

const OUT = path.join("src", "schema", "generated.ts");
const GROUPS = [
  { name: "CORE", path: "src/types.ts", types: ["WorkflowState", "Role", "NewItem", "Handoff"] },
  { name: "SCRUM", path: "src/scrum/config.ts", types: ["ScrumConfig"] },
  { name: "KANBAN", path: "src/kanban/config.ts", types: ["KanbanConfig"] },
  { name: "WATERFALL", path: "src/waterfall/config.ts", types: ["WaterfallConfig"] },
];

function definitionsFor(group) {
  const generator = createGenerator({
    path: group.path,
    tsconfig: "tsconfig.json",
    skipTypeCheck: true,
    jsDoc: "basic",
    expose: "export",
    topRef: true,
    additionalProperties: false,
    sortProps: true,
  });
  const definitions = {};
  for (const type of group.types) {
    const schema = generator.createSchema(type);
    for (const [name, def] of Object.entries(schema.definitions ?? {})) {
      const seen = definitions[name];
      if (seen && JSON.stringify(seen) !== JSON.stringify(def))
        throw new Error(
          `${group.path}: definition ${name} differs between ${group.types.join(", ")}`,
        );
      definitions[name] = def;
    }
  }
  // sorted keys so the output is stable across runs and machines
  return Object.fromEntries(
    Object.keys(definitions)
      .sort()
      .map((k) => [k, definitions[k]]),
  );
}

function render() {
  const lines = [
    "// GENERATED by scripts/gen-schema.mjs from src/types.ts and src/{scrum,kanban,waterfall}/config.ts.",
    "// Do not edit. Run `pnpm schema:gen`; `pnpm schema:check` fails the build when this file is stale.",
    'import type { JsonSchema } from "./types.ts";',
    "",
  ];
  for (const group of GROUPS) {
    lines.push(
      `export const ${group.name}_DEFINITIONS: Record<string, JsonSchema> = ${JSON.stringify(definitionsFor(group), null, 2)};`,
      "",
    );
  }
  return lines.join("\n");
}

function format(file) {
  const r = spawnSync(process.platform === "win32" ? "pnpm.cmd" : "pnpm", ["exec", "oxfmt", file], {
    stdio: "inherit",
    shell: process.platform === "win32",
  });
  if (r.status !== 0) throw new Error(`oxfmt failed on ${file}`);
}

const check = process.argv.includes("--check");
if (!check) {
  writeFileSync(OUT, render());
  format(OUT);
  console.log(`wrote ${OUT}`);
} else {
  const dir = mkdtempSync(path.join(tmpdir(), "exwf-schema-"));
  const tmp = path.join(dir, "generated.ts");
  try {
    writeFileSync(tmp, render());
    format(tmp);
    const fresh = readFileSync(tmp, "utf8");
    const committed = readFileSync(OUT, "utf8");
    if (fresh !== committed) {
      const a = fresh.split("\n");
      const b = committed.split("\n");
      const i = Array.from({ length: Math.max(a.length, b.length) }, (_, n) => n).find(
        (n) => a[n] !== b[n],
      );
      console.error(
        `FAIL ${OUT} is stale (first difference at line ${i + 1}):\n  fresh:     ${a[i]}\n  committed: ${b[i]}`,
      );
      console.error("run `pnpm schema:gen` and commit the result");
      process.exit(1);
    }
    console.log(`ok ${OUT} matches the types`);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}
